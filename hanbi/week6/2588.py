# 사용자 입력
num1 = int(input())
num2 = int(input())

# 일의 자리 수 계산 (10으로 나눴을 때 나머지)
print(num1 * (num2 % 10))

# 십의 자리 수 계산 (10으로 나눴을 때 몫을 다시 10으로 나누고 나머지 구함)
print(num1 * ((num2 // 10) % 10))

# 백의 자리 수 계산 (100으로 나눴을 때 몫을 다시 10으로 나누고 나머지 구함)
print(num1 * (num2 // 100)) 

# 두 숫자의 전체 곱셈 결과 
print(num1 * num2) 